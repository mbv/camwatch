package live

import "testing"

func TestInspectAnnexB_HEVC(t *testing.T) {
	// VPS(32)=0x40, SPS(33)=0x42, PPS(34)=0x44, IDR(19)=0x26
	buf := []byte{
		0x00, 0x00, 0x00, 0x01, 0x02, 0x01, 0xff, // TRAIL junk before keyframe
		0x00, 0x00, 0x00, 0x01, 0x40, 0x01, 0xaa,
		0x00, 0x00, 0x00, 0x01, 0x42, 0x01, 0xbb,
		0x00, 0x00, 0x00, 0x01, 0x44, 0x01, 0xcc,
		0x00, 0x00, 0x00, 0x01, 0x26, 0x01, 0xdd,
		0x00, 0x00, 0x00, 0x01, 0x02, 0x01, 0xee, // P after IDR kept
	}
	syn, ok := inspectAnnexB(buf)
	if !ok || syn.Format != "hevc" {
		t.Fatalf("got ok=%v %+v", ok, syn)
	}
	if syn.Prefix[4] != 0x40 { // must start at VPS, not TRAIL junk
		t.Fatalf("prefix should start at VPS, head=%x", syn.Prefix[:8])
	}
	if len(syn.Prefix) >= len(buf) {
		t.Fatalf("expected trimmed prefix len=%d buf=%d", len(syn.Prefix), len(buf))
	}
}

func TestInspectAnnexB_HEVCNeedsIDR(t *testing.T) {
	buf := []byte{
		0x00, 0x00, 0x00, 0x01, 0x40, 0x01,
		0x00, 0x00, 0x00, 0x01, 0x42, 0x01,
		0x00, 0x00, 0x00, 0x01, 0x44, 0x01,
		0x00, 0x00, 0x00, 0x01, 0x02, 0x01, // TRAIL_R only
	}
	if _, ok := inspectAnnexB(buf); ok {
		t.Fatal("expected no sync without IDR")
	}
}

func TestInspectAnnexB_H264(t *testing.T) {
	buf := []byte{
		0x00, 0x00, 0x00, 0x01, 0x61, 0x01, // non-IDR junk
		0x00, 0x00, 0x00, 0x01, 0x67, 0x42, // SPS
		0x00, 0x00, 0x00, 0x01, 0x68, 0xce, // PPS
		0x00, 0x00, 0x00, 0x01, 0x65, 0x88, // IDR
	}
	syn, ok := inspectAnnexB(buf)
	if !ok || syn.Format != "h264" {
		t.Fatalf("got ok=%v %+v", ok, syn)
	}
	if syn.Prefix[4]&0x1f != 7 {
		t.Fatalf("expected SPS start, got %x", syn.Prefix[4])
	}
}
